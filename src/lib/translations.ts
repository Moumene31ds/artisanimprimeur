export function normalizeLanguage(language?: string | null): LanguageCode {
  if (language === "fr") return "fr";
  return "ar";
}

export function getLanguageDirection(language?: string | null): "rtl" | "ltr" {
  return normalizeLanguage(language) === "ar" ? "rtl" : "ltr";
}

export function getTranslation(language: string | null | undefined, key: string, fallback?: string): string {
  const normalizedLanguage = normalizeLanguage(language);
  const source = TRANSLATIONS[normalizedLanguage] as Record<string, string>;
  const value = source?.[key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key as keyof (typeof TRANSLATIONS)[typeof DEFAULT_LANGUAGE]] ?? fallback ?? key;
  return value;
}

export function createTranslator(language: string | null | undefined) {
  return (key: string, fallback?: string) => getTranslation(language, key, fallback);
}

export function getLanguageLabel(language?: string | null): string {
  return normalizeLanguage(language) === "fr" ? "Français" : "العربية";
}
